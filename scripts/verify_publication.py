"""Verify the actual Pages publication, not merely a successful gh-pages push.

A blocked dashboard can be correctly published. This verifies delivery only;
the workflow's following health gate still fails for blocked observations.
"""
import argparse
from pathlib import Path
import time
from urllib.error import URLError
from urllib.request import Request, urlopen

PUBLIC_URL = "https://keresell-coder.github.io/oslo-screener-dashboard/"
FILES = ("health.json", "index.html")


def fetch_bytes(url, timeout):
    request = Request(url, headers={
        "Cache-Control": "no-cache", "User-Agent": "oslo-dashboard-publication-check/1.0",
    })
    with urlopen(request, timeout=timeout) as response:
        return response.read()


def verify(directory=Path("site"), timeout=600, interval=15, *,
           fetch=fetch_bytes, clock=time.monotonic, sleep=time.sleep):
    """Retry boundedly until both public files equal the exact generated bytes."""
    if timeout <= 0 or interval <= 0:
        raise ValueError("timeout and interval must be positive")
    expected = {name: (Path(directory) / name).read_bytes() for name in FILES}
    deadline = clock() + timeout
    last_error = "publication not checked"
    while clock() < deadline:
        try:
            for name, content in expected.items():
                remaining = deadline - clock()
                if remaining <= 0:
                    raise TimeoutError("publication verification deadline reached")
                actual = fetch(PUBLIC_URL + name, timeout=min(20, remaining))
                if actual != content:
                    raise ValueError(f"public {name} does not match this build")
            if clock() <= deadline:
                return
        except (OSError, URLError, ValueError) as exc:
            last_error = str(exc)
        remaining = deadline - clock()
        if remaining > 0:
            sleep(min(interval, remaining))
    raise RuntimeError(f"Pages publication not verified within {timeout}s: {last_error}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", default="site")
    parser.add_argument("--timeout", type=float, default=600)
    args = parser.parse_args()
    verify(Path(args.directory), args.timeout)
    print("Verified live health.json and index.html match this build exactly.")
